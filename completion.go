// ---- shell completion --------------------------------------------------------

// The lists below are the single source of truth for both shell scripts: when
// a subcommand or flag is added (to main's dispatch, parseCLI, or runCert),
// extend the matching slice here and every shell picks it up.
var (
	completionSubcommands = []string{"cert", "curl", "completion", "history", "view", "version", "help"}
	completionMethods     = []string{"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"}
	// Flags of a plain `weeb [METHOD] URL …` invocation (see parseCLI).
	completionMainFlags = []string{
		"-H", "--header", "-d", "--data", "-X", "--request", "--timeout",
		"-v", "--stats", "--pretty", "--raw", "--no-tui", "--headless",
		"-q", "--quiet", "--persona", "--to-curl", "-o", "--output",
		"--max-body", "-h", "--help",
	}
	// Flags accepted after `weeb cert` (see runCert).
	completionCertFlags = []string{
		"-k", "--insecure", "--json", "--pem", "--showcerts", "--brief",
		"--short", "--sni", "--servername", "--starttls", "--alpn", "--tls",
		"--client-cert", "--cert", "--client-key", "--key", "--timeout",
		"--persona",
		"-f", "--file", "--host",
	}
	// Flags accepted after `weeb view` (see parseViewArgs).
	completionViewFlags = []string{
		"--type", "--raw", "--max-body", "-h", "--help",
	}
	completionPersonas = []string{"plain", "dere", "tsun", "yan"}
)

// runCompletion handles `weeb completion zsh|bash|fish`: print a static
// completion script to w (stdout in main), ready to eval (bash), drop in
// $fpath (zsh), or save under ~/.config/fish/completions (fish).
func runCompletion(args []string, w io.Writer) int {
	if len(args) != 1 {
		fmt.Fprintln(os.Stderr, "weeb: completion needs a shell: weeb completion zsh|bash|fish")
		return 2
	}
	switch args[0] {
	case "zsh":
		fmt.Fprint(w, zshCompletion())
		return 0
	case "bash":
		fmt.Fprint(w, bashCompletion())
		return 0
	case "fish":
		fmt.Fprint(w, fishCompletion())
		return 0
	default:
		fmt.Fprintf(os.Stderr, "weeb: unsupported shell %q: weeb completion zsh|bash|fish\n", args[0])
		return 2
	}
}

// zshCompletion renders the zsh script with the shared lists spliced in.
func zshCompletion() string {
	return fmt.Sprintf(`#compdef weeb
# zsh completion for weeb — generated by 'weeb completion zsh'.
# The command/flag lists are emitted from completion.go; update them there.

_weeb() {
  local -a subcmds methods mainflags certflags personas
  subcmds=(%[1]s)
  methods=(%[2]s)
  mainflags=(%[3]s)
  certflags=(%[4]s)
  personas=(%[5]s)
  local -a viewflags
  viewflags=(%[6]s)

  # Flags whose value we can complete.
  case "${words[CURRENT-1]}" in
    --persona) compadd -a personas; return ;;
    --type) compadd json xml html yaml md; return ;;
    -X|--request) compadd -a methods; return ;;
    -o|--output|-d|--data|--client-cert|--cert|--client-key|--key) _files; return ;;
    -f|--file) _files; return ;;
  esac

  # First word: a subcommand, a method, or straight to flags/URL.
  if (( CURRENT == 2 )); then
    compadd -a subcmds methods mainflags
    return
  fi

  case "${words[2]}" in
    cert|tls)   _arguments $certflags '*:host:_hosts' ;;
    completion) (( CURRENT == 3 )) && compadd zsh bash fish ;;
    view)       _arguments $viewflags '*:file:_files' ;;
    curl|import|version|help) ;;
    *)          _arguments $mainflags '*:url:_urls' ;;
  esac
}

_weeb "$@"
`,
		strings.Join(completionSubcommands, " "),
		strings.Join(completionMethods, " "),
		strings.Join(completionMainFlags, " "),
		strings.Join(completionCertFlags, " "),
		strings.Join(completionPersonas, " "),
		strings.Join(completionViewFlags, " "),
	)
}

// bashCompletion renders the bash script with the shared lists spliced in.
func bashCompletion() string {
	return fmt.Sprintf(`# bash completion for weeb — generated by 'weeb completion bash'.
# The command/flag lists are emitted from completion.go; update them there.

_weeb() {
  local cur prev
  cur="${COMP_WORDS[COMP_CWORD]}"
  prev="${COMP_WORDS[COMP_CWORD-1]}"

  local subcmds="%[1]s"
  local methods="%[2]s"
  local mainflags="%[3]s"
  local certflags="%[4]s"
  local personas="%[5]s"
  local viewflags="%[6]s"

  # Flags whose value we can complete.
  case "$prev" in
    --persona) COMPREPLY=($(compgen -W "$personas" -- "$cur")); return ;;
    --type) COMPREPLY=($(compgen -W "json xml html yaml md" -- "$cur")); return ;;
    -X|--request) COMPREPLY=($(compgen -W "$methods" -- "$cur")); return ;;
    -o|--output|-d|--data|--client-cert|--cert|--client-key|--key)
      COMPREPLY=($(compgen -f -- "$cur")); return ;;
    -f|--file) COMPREPLY=($(compgen -f -- "$cur")); return ;;
  esac

  # First word: a subcommand, a method, or straight to flags/URL.
  if (( COMP_CWORD == 1 )); then
    COMPREPLY=($(compgen -W "$subcmds $methods $mainflags" -- "$cur"))
    return
  fi

  case "${COMP_WORDS[1]}" in
    cert|tls)   COMPREPLY=($(compgen -W "$certflags" -- "$cur")) ;;
    completion) COMPREPLY=($(compgen -W "zsh bash fish" -- "$cur")) ;;
    view)       COMPREPLY=($(compgen -W "$viewflags" -- "$cur") $(compgen -f -- "$cur")) ;;
    curl|import|version|help) ;;
    *)          COMPREPLY=($(compgen -W "$mainflags" -- "$cur")) ;;
  esac
}

complete -F _weeb weeb
`,
		strings.Join(completionSubcommands, " "),
		strings.Join(completionMethods, " "),
		strings.Join(completionMainFlags, " "),
		strings.Join(completionCertFlags, " "),
		strings.Join(completionPersonas, " "),
		strings.Join(completionViewFlags, " "),
	)
}

// fishCompletion renders the fish script. fish wants one `complete` line per
// option rather than a word list, so instead of splicing the lists into a
// template it walks them: a flag added to completionMainFlags or
// completionCertFlags (or a new subcommand, method or persona) lands here
// with no change to this function.
func fishCompletion() string {
	var b strings.Builder
	b.WriteString(`# fish completion for weeb — generated by 'weeb completion fish'.
# The command/flag lists are emitted from completion.go; update them there.
# Install: weeb completion fish > ~/.config/fish/completions/weeb.fish

# URLs and hosts aren't files: no file completion unless a flag asks for it.
complete -c weeb -f

# First word: a subcommand, a method, or straight to flags/URL.
`)
	fmt.Fprintf(&b, "complete -c weeb -n __fish_use_subcommand -a %s\n", fishWords(completionSubcommands))
	fmt.Fprintf(&b, "complete -c weeb -n __fish_use_subcommand -a %s\n", fishWords(completionMethods))
	b.WriteString("complete -c weeb -n '__fish_seen_subcommand_from completion' -a 'zsh bash fish'\n")

	// A plain `weeb [METHOD] URL` takes the main flags until a subcommand (or
	// one of the aliases main also dispatches on) has been typed.
	subcmds := append(append([]string{}, completionSubcommands...), "tls", "import")
	fmt.Fprintf(&b, `
# Flags of a plain `+"`weeb [METHOD] URL …`"+` request: no subcommand typed yet.
function __weeb_plain_request
    not __fish_seen_subcommand_from %s
end
`, strings.Join(subcmds, " "))
	writeFishFlags(&b, "__weeb_plain_request", completionMainFlags)
	b.WriteString("\n# Flags of `weeb cert HOST`.\n")
	writeFishFlags(&b, "__fish_seen_subcommand_from cert tls", completionCertFlags)
	b.WriteString("\n# `weeb view [FILE|-]`: its flags, and file names (overriding the global -f, no-files).\n")
	writeFishFlags(&b, "__fish_seen_subcommand_from view", completionViewFlags)
	b.WriteString("complete -c weeb -n '__fish_seen_subcommand_from view' -F\n")
	return b.String()
}

// writeFishFlags emits one `complete` line per flag, gated on cond.
func writeFishFlags(b *strings.Builder, cond string, flags []string) {
	for _, f := range flags {
		fmt.Fprintf(b, "complete -c weeb -n %s %s%s\n", fishQuote(cond), fishOpt(f), fishFlagValue(f))
	}
}

// fishOpt maps one list entry to fish's option syntax: --long is `-l long`,
// a single-letter -x is `-s x`, and anything else (an old-style -long) is
// `-o long`.
func fishOpt(flag string) string {
	switch {
	case strings.HasPrefix(flag, "--"):
		return "-l " + flag[2:]
	case len(flag) == 2:
		return "-s " + flag[1:]
	default:
		return "-o " + strings.TrimPrefix(flag, "-")
	}
}

// fishFlagValue completes the values of the same flags the zsh and bash
// scripts special-case: -x (exclusive) takes a word from a list, -r -F takes
// a file path.
func fishFlagValue(flag string) string {
	switch flag {
	case "--persona":
		return " -x -a " + fishWords(completionPersonas)
	case "-X", "--request":
		return " -x -a " + fishWords(completionMethods)
	case "--type":
		return " -x -a " + fishWords([]string{"json", "xml", "html", "yaml", "md"})
	case "-o", "--output", "-d", "--data", "--client-cert", "--cert", "--client-key", "--key", "-f", "--file":
		return " -r -F"
	}
	return ""
}

// fishWords renders a word list as one single-quoted fish argument.
func fishWords(words []string) string { return fishQuote(strings.Join(words, " ")) }

// fishQuote single-quotes s for fish, where only \ and ' are special inside
// single quotes. The lists hold plain words today; quoting keeps a future
// entry from breaking the script.
func fishQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}
